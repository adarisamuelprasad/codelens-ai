-- Written to run unchanged on PostgreSQL (production) and H2 (local runs, tests).

CREATE TABLE review (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    repo            VARCHAR(200)  NOT NULL,
    pr_number       INTEGER       NOT NULL,
    pr_title        VARCHAR(1000),
    head_sha        VARCHAR(64),
    trigger_source  VARCHAR(20)   NOT NULL,   -- WEBHOOK or MANUAL
    status          VARCHAR(20)   NOT NULL,   -- QUEUED, RUNNING, DONE, FAILED
    files_analyzed  INTEGER       NOT NULL DEFAULT 0,
    files_skipped   INTEGER       NOT NULL DEFAULT 0,
    ai_used         BOOLEAN       NOT NULL DEFAULT FALSE,
    comment_posted  BOOLEAN       NOT NULL DEFAULT FALSE,
    error           VARCHAR(2000),
    created_at      TIMESTAMP WITH TIME ZONE NOT NULL,
    finished_at     TIMESTAMP WITH TIME ZONE,
    duration_ms     BIGINT
);

CREATE INDEX review_repo_pr ON review (repo, pr_number);
CREATE INDEX review_created ON review (created_at);

CREATE TABLE finding (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    review_id       BIGINT        NOT NULL REFERENCES review (id) ON DELETE CASCADE,
    rule_id         VARCHAR(100)  NOT NULL,
    source          VARCHAR(20)   NOT NULL,   -- pmd or codelens
    category        VARCHAR(20)   NOT NULL,
    severity        VARCHAR(10)   NOT NULL,
    file_path       VARCHAR(500)  NOT NULL,
    line            INTEGER       NOT NULL,
    message         VARCHAR(2000) NOT NULL,
    snippet         VARCHAR(8000),
    explanation     VARCHAR(4000),
    suggested_fix   VARCHAR(4000),
    ai_verdict      VARCHAR(30),               -- true_positive, likely_false_positive, or null when no AI
    ai_verdict_reason VARCHAR(1000),
    -- Human label for evaluation: CONFIRMED (actionable), REJECTED (false positive), or null.
    human_label     VARCHAR(20)
);

CREATE INDEX finding_review ON finding (review_id);
